#!/usr/bin/env python3
"""Render RAS-ready LaTeX tables from frozen GOOSE result records."""

import argparse
import json
from pathlib import Path

from render_goose_manuscript_results import (
    CLASS_METRICS,
    CONTROL_STEM,
    CORE_METRICS,
    DISTANCE_BINS,
    METHOD_STEM,
    MONO_STEM,
    VISIBILITY_METRICS,
    mean_std,
    number,
    read_csv,
    render,
    require_int,
    require_one,
    scalar,
)


METRIC_LABELS = {
    'SC_IoU': 'SC-IoU',
    'SSC_mIoU': 'SSC-mIoU',
    'V-SC-IoU': 'V-SC-IoU',
    'V-SSC-mIoU': 'V-SSC-mIoU',
    'O-SC-IoU': 'O-SC-IoU',
    'O-SSC-mIoU': 'O-SSC-mIoU',
}


def latex_value(value):
    return value.replace('+/-', r'$\pm$')


def load_lifting_result(path):
    payload = json.loads(Path(path).read_text(encoding='utf-8'))
    if payload.get('num_samples') != 469:
        raise ValueError('Geometric lifting result must contain 469 targets')
    contract = payload.get('prediction_contract', {})
    if contract.get('shape') != [200, 128, 32] \
            or contract.get('axis_order') != 'x,y,z' \
            or contract.get('class_ids') != '0..7':
        raise ValueError('Invalid geometric lifting prediction contract')
    if 'no OCC/LiDAR/mask training' not in payload.get('supervision', ''):
        raise ValueError('Geometric lifting supervision boundary is missing')
    row = {}
    row['SC_IoU'] = payload['full_grid']['SC-IoU'] * 100.0
    row['SSC_mIoU'] = payload['full_grid']['SSC-mIoU'] * 100.0
    for metric in VISIBILITY_METRICS:
        row[metric] = payload['visibility'][metric] * 100.0
    for distance_bin in DISTANCE_BINS:
        domains = payload['visibility']['by_horizontal_range'][distance_bin]
        for metric in VISIBILITY_METRICS:
            domain = 'visible' if metric.startswith('V-') else 'occluded'
            native = metric[2:]
            row['{}_{}'.format(metric, distance_bin)] = (
                domains[domain][native] * 100.0)
    per_class = payload['full_grid']['per_class']
    for _, metric in CLASS_METRICS:
        class_name = metric.replace('IoU_', '')
        value = per_class[class_name]['iou']
        row[metric] = float('nan') if value is None else value * 100.0
    return row


def table(headers, rows, caption, label, widths=None):
    columns = widths or ('l' + 'c' * (len(headers) - 1))
    lines = [
        r'\begin{table*}[t]',
        r'\centering',
        r'\caption{' + caption + r'}\label{' + label + r'}',
        r'\scriptsize',
        r'\resizebox{\textwidth}{!}{%',
        r'\begin{tabular}{' + columns + r'}',
        r'\toprule',
        ' & '.join(headers) + r' \\',
        r'\midrule',
    ]
    lines.extend(' & '.join(row) + r' \\' for row in rows)
    lines.extend([
        r'\bottomrule',
        r'\end{tabular}}',
        r'\end{table*}',
        '',
    ])
    return lines


def render_latex(multiseed_path, paired_path, external_path, gate_path,
                 lifting_path=None):
    # Reuse the canonical renderer as a fail-closed contract check first.
    render(multiseed_path, paired_path, external_path, gate_path)
    multiseed = read_csv(multiseed_path)
    paired = read_csv(paired_path)
    external = read_csv(external_path)
    gate = json.loads(Path(gate_path).read_text(encoding='utf-8'))
    mono = require_one(multiseed, 'run_stem', MONO_STEM, multiseed_path)
    control = require_one(multiseed, 'run_stem', CONTROL_STEM, multiseed_path)
    method = require_one(multiseed, 'run_stem', METHOD_STEM, multiseed_path)
    upper = external[0]
    lifting = load_lifting_result(lifting_path) if lifting_path else None
    require_int(mono, 'num_seeds', 3, 'mono aggregate')
    require_int(control, 'num_seeds', 5, 'temporal control aggregate')
    require_int(method, 'num_seeds', 5, 'pose-guided aggregate')

    lines = [
        '% Machine-generated by tools/render_goose_latex_results.py.',
        '% Do not edit quantitative values by hand.',
        '',
    ]
    main_rows = []
    variants = []
    if lifting is not None:
        variants.append((
            'Geometric lifting', 'Train-2D semantics + pseudo-depth lift',
            lifting, False))
    variants.extend((
        ('Mono', 'Image-space weak', mono, True),
        ('Temporal control', 'Image-space weak', control, True),
        ('Pose-guided', 'Image-space weak', method, True),
        ('SurroundOcc', 'Fully supervised OCC GT', upper, False)))
    for label, supervision, row, aggregate in variants:
        values = [
            latex_value(mean_std(row, metric, label)) if aggregate
            else scalar(row, metric, label)
            for metric in CORE_METRICS]
        main_rows.append([label, supervision] + values)
    lines.extend(table(
        ['Variant', 'Training supervision']
        + [METRIC_LABELS[item] for item in CORE_METRICS],
        main_rows,
        ('Main comparison on the 469-target common validation set. '
         'Learned Gaussian entries report mean $\pm$ sample standard '
         'deviation; '
         'mono uses $n=3$, temporal variants use $n=5$. Geometric lifting is '
         'a deterministic final-checkpoint baseline. SurroundOcc is an '
         'OCC-GT upper bound, not a supervision-matched baseline.'),
        'tab:main_results'))

    paired_rows = []
    for metric in CORE_METRICS:
        row = require_one(paired, 'metric', metric, paired_path)
        paired_rows.append([
            METRIC_LABELS[metric],
            *['{:+.2f}'.format(number(
                row, 'seed{}_delta'.format(seed), metric))
              for seed in range(5)],
            latex_value('{:+.2f} +/- {:.2f}'.format(
                number(row, 'delta_mean', metric),
                number(row, 'delta_std', metric))),
        ])
    lines.extend(table(
        ['Metric', 'Seed 0', 'Seed 1', 'Seed 2', 'Seed 3', 'Seed 4',
         'Mean $\pm$ s.d.'],
        paired_rows,
        ('Identical-seed pose-guided minus temporal-control differences. '
         'The five pairs audit variability; no significance test was '
         'performed.'),
        'tab:paired_deltas'))

    distance_rows = []
    distance_variants = []
    if lifting is not None:
        distance_variants.append(('Geometric lifting', lifting, False))
    distance_variants.extend((
        ('Temporal control', control, True),
        ('Pose-guided', method, True)))
    for label, row, aggregate in distance_variants:
        for distance_bin in DISTANCE_BINS:
            distance_rows.append([
                label, distance_bin.replace('m', ' m'),
                *[(latex_value(mean_std(
                    row, '{}_{}'.format(metric, distance_bin),
                    '{} {}'.format(label, distance_bin))) if aggregate
                   else scalar(row, '{}_{}'.format(metric, distance_bin),
                               '{} {}'.format(label, distance_bin)))
                  for metric in VISIBILITY_METRICS],
            ])
    lines.extend(table(
        ['Variant', 'Range']
        + [METRIC_LABELS[item] for item in VISIBILITY_METRICS],
        distance_rows,
        ('Visible/occluded metrics by horizontal radial range. Temporal '
         'variants report mean $\pm$ sample standard deviation over five '
         'seeds; geometric lifting is deterministic.'),
        'tab:distance_results'))

    class_rows = []
    class_variants = []
    if lifting is not None:
        class_variants.append(('Geometric lifting', lifting, False))
    class_variants.extend((
        ('Mono', mono, True), ('Temporal control', control, True),
        ('Pose-guided', method, True), ('SurroundOcc', upper, False)))
    for label, row, aggregate in class_variants:
        class_rows.append([
            label,
            *[(latex_value(mean_std(row, metric, label)) if aggregate
               else scalar(row, metric, label))
              for _, metric in CLASS_METRICS],
        ])
    lines.extend(table(
        ['Variant'] + [name.title() for name, _ in CLASS_METRICS],
        class_rows,
        ('Per-class full-grid IoU. Learned Gaussian entries report mean '
         '$\pm$ sample standard deviation; the full grid retains the '
         'unknown-as-free convention.'),
        'tab:per_class'))
    lines.extend([
        r'\paragraph{Predeclared claim gate.}',
        ('The frozen gate selects the \emph{%s} narrative. %s No '
         'significance test was performed.' % (
             gate['narrative'].replace('-', r'\-'),
             gate['interpretation'])),
        '',
    ])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--multiseed-csv', default='work_dir/goose_experiment_multiseed_summary.csv')
    parser.add_argument('--paired-csv', default='work_dir/goose_experiment_paired_deltas.csv')
    parser.add_argument('--external-csv', default='work_dir/goose_external_baseline_summary.csv')
    parser.add_argument('--claim-gate', default='work_dir/goose_claim_gate.json')
    parser.add_argument('--lifting-result', default=(
        'work_dir/goose_geometric_lifting_common10/goose_visibility_val.json'))
    parser.add_argument('--output', default='paper/goose_occ_manuscript/ras_submission/generated_results.tex')
    args = parser.parse_args()
    text = render_latex(
        args.multiseed_csv, args.paired_csv, args.external_csv, args.claim_gate,
        args.lifting_result)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text + '\n', encoding='utf-8')
    print('Rendered {}'.format(output))


if __name__ == '__main__':
    main()
